import { fireEvent, render, screen, within } from '@testing-library/react';
import { act } from 'react';
import { describe, expect, test, vi } from 'vitest';
import { ApiError } from '../../data/errors';
import type { DisplayPrefs } from '../../lib/format';
import { fixtureSystem, fixtureSystemBare } from '../help/fixtures';
import { formatAbsolute, SystemSection } from './system-section';

const prefs: DisplayPrefs = {
  locale: 'en',
  timezone: 'Europe/Stockholm',
  dateFormat: 'MMM d',
  timeFormat: '24h',
};
const now = Date.UTC(2026, 9, 10, 12, 0, 0);

const item = (id: string) => screen.getByTestId(`system-${id}`).textContent ?? '';

describe('Admin → System (AC-11.5, 08 §9)', () => {
  test('shows every item: version, uptime, database and WAL, backup, jobs, SMTP, push, SSE, storage, counts', () => {
    render(
      <SystemSection
        system={fixtureSystem(now)}
        error={null}
        onRefresh={vi.fn()}
        prefs={prefs}
        now={now}
      />,
    );
    expect(item('version')).toBe('Version1.5.0commit 7e6a2dd4c1f0');
    expect(item('started')).toBe('Started3 days ago');
    expect(item('database')).toBe('Database46.1 MBwrite-ahead log 3.9 MB');
    expect(item('backup')).toContain('9 hours ago');
    expect(item('backup')).toContain('auto-2026-10-10T02-00-00Z.sqlite');
    expect(item('smtp')).toBe('Email (SMTP)Configured');
    expect(item('push')).toBe('Push notificationsKeys generated by rooster7 devices subscribed');
    expect(item('sse')).toBe('Live connections4');
    expect(item('storage')).toBe(
      'Attachments1.2 GB in 2,816 fileson the local diskEach user can store up to 1 GB',
    );
    expect(item('counts')).toBe('Usage12 users·5 organisations·4,208 tasks');
    const jobs = screen.getByTestId('system-jobs');
    const rows = within(jobs).getAllByRole('row').slice(1);
    expect(rows.map((r) => r.textContent)).toEqual([
      'backup9 hours agoOK',
      'purge8 hours agoOK',
      'due-remindersjust nowOK',
      'email-batch3 minutes agoFailedconnect ECONNREFUSED 10.0.0.25:587',
      'blob-gc–Not run yet',
    ]);
  });

  test('Send test email (ADR 0059): says where it went, or what the mail server answered', async () => {
    const onRun = vi
      .fn()
      .mockResolvedValueOnce({ to: 'ada@example.com' })
      .mockRejectedValueOnce(
        new ApiError(
          'mail_failed',
          502,
          'The mail server did not accept the message (SMTP send failed (EAUTH): 535 after AUTH PLAIN).',
        ),
      );
    render(
      <SystemSection
        system={fixtureSystem(now)}
        error={null}
        onRefresh={vi.fn()}
        prefs={prefs}
        now={now}
        mailTest={{ onRun, online: true }}
      />,
    );
    const smtp = screen.getByTestId('system-smtp');
    const button = within(smtp).getByRole('button', { name: 'Send test email' });
    await act(async () => fireEvent.click(button));
    expect(within(smtp).getByRole('status').textContent).toBe(
      'Sent to ada@example.com. The mail server accepted it; check that inbox.',
    );
    await act(async () => fireEvent.click(button));
    const alert = within(smtp).getByRole('alert');
    expect(alert.textContent).toContain('The test email didn’t go out.');
    expect(alert.textContent).toContain('535 after AUTH PLAIN');
    expect(onRun).toHaveBeenCalledTimes(2);
  });

  test('without SMTP there is nothing to test', () => {
    const system = { ...fixtureSystem(now), smtp: { configured: false } };
    render(
      <SystemSection
        system={system}
        error={null}
        onRefresh={vi.fn()}
        prefs={prefs}
        now={now}
        mailTest={{ onRun: vi.fn(), online: true }}
      />,
    );
    expect(screen.queryByRole('button', { name: 'Send test email' })).toBeNull();
  });

  test('times show the exact moment on focus, as a tooltip', () => {
    render(
      <SystemSection
        system={fixtureSystem(now)}
        error={null}
        onRefresh={vi.fn()}
        prefs={prefs}
        now={now}
      />,
    );
    const started = within(screen.getByTestId('system-started')).getByText('3 days ago');
    expect(started.tagName).toBe('TIME');
    expect(started.getAttribute('tabindex')).toBe('0');
    expect(formatAbsolute(Date.UTC(2026, 9, 10, 8, 0, 0), prefs)).toBe('Oct 10, 2026, 10:00:00');
  });

  test('a fresh instance: no backup, SMTP or push, S3 without a quota', () => {
    render(
      <SystemSection
        system={fixtureSystemBare(now)}
        error={null}
        onRefresh={vi.fn()}
        prefs={prefs}
        now={now}
      />,
    );
    expect(item('version')).toBe('Version1.5.0');
    expect(item('backup')).toBe('Last backupNo backups yet');
    expect(item('smtp')).toBe('Email (SMTP)Not configured');
    expect(item('push')).toBe('Push notificationsOff0 devices subscribed');
    expect(item('storage')).toContain('in S3 storage');
    expect(item('storage')).toContain('No storage limit per user');
    expect(screen.getByText('No scheduled jobs.')).toBeTruthy();
  });

  test('Refresh reads it again; loading and failure states', () => {
    const onRefresh = vi.fn();
    const { rerender } = render(
      <SystemSection
        system={undefined}
        error={null}
        onRefresh={onRefresh}
        prefs={prefs}
        now={now}
      />,
    );
    expect(screen.getByRole('status', { name: 'Loading the system status…' })).toBeTruthy();
    fireEvent.click(screen.getByRole('button', { name: 'Refresh' }));
    expect(onRefresh).toHaveBeenCalledTimes(1);
    rerender(
      <SystemSection
        system={undefined}
        error={new Error('500')}
        onRefresh={onRefresh}
        prefs={prefs}
        now={now}
      />,
    );
    expect(screen.getByRole('alert').textContent).toContain('Couldn’t load the system status');
    rerender(
      <SystemSection
        system={fixtureSystem(now)}
        error={new Error('500')}
        onRefresh={onRefresh}
        prefs={prefs}
        now={now}
      />,
    );
    expect(screen.getByRole('alert').textContent).toContain('the last one that loaded');
    expect(screen.getByTestId('system-version')).toBeTruthy();
  });

  test('Rebuild search index asks inline, then says what it indexed', async () => {
    const onRun = vi.fn().mockResolvedValue({ indexed: 4208, durationMs: 184 });
    render(
      <SystemSection
        system={fixtureSystem(now)}
        error={null}
        onRefresh={vi.fn()}
        prefs={prefs}
        now={now}
        reindex={{ onRun, online: true }}
      />,
    );
    const block = screen.getByTestId('system-reindex');
    fireEvent.click(within(block).getByRole('button', { name: 'Rebuild search index' }));
    expect(onRun).not.toHaveBeenCalled();
    expect(document.activeElement).toBe(within(block).getByRole('button', { name: 'Cancel' }));
    await act(async () => {
      fireEvent.click(within(block).getByRole('button', { name: 'Rebuild' }));
    });
    expect(onRun).toHaveBeenCalledTimes(1);
    expect(within(block).getByRole('status').textContent).toBe(
      'Search index rebuilt: 4,208 tasks in 184 ms.',
    );
    expect(document.activeElement).toBe(
      within(block).getByRole('button', { name: 'Rebuild search index' }),
    );
  });

  test('a failed rebuild says so; offline the action is disabled', async () => {
    const onRun = vi.fn().mockRejectedValue(new Error('500'));
    const { rerender } = render(
      <SystemSection
        system={fixtureSystem(now)}
        error={null}
        onRefresh={vi.fn()}
        prefs={prefs}
        now={now}
        reindex={{ onRun, online: true, defaultConfirming: true }}
      />,
    );
    await act(async () => {
      fireEvent.click(screen.getByRole('button', { name: 'Rebuild' }));
    });
    expect(screen.getByRole('alert').textContent).toBe(
      'Couldn’t rebuild the search index. Try again.',
    );
    rerender(
      <SystemSection
        system={fixtureSystem(now)}
        error={null}
        onRefresh={vi.fn()}
        prefs={prefs}
        now={now}
        reindex={{ onRun, online: false }}
      />,
    );
    expect(
      screen.getByRole('button', { name: 'Rebuild search index' }).hasAttribute('disabled'),
    ).toBe(true);
    expect(screen.getByText(/You’re offline/)).toBeTruthy();
  });
});
