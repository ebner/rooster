/**
 * NL date corpus (10 §3.1). Each row:
 * `[locale, mode, input, today, weekStart, expected | null, remainingTitle?]`
 * - `expected` is `YYYY-MM-DD` or `YYYY-MM-DD HH:MM`; `null` means "no match".
 * - `remainingTitle` (title rows) is `stripTitleMatch` of the match.
 * - Picker rows use `dateFormat` `MMM d` for `en` and `d MMM` for `sv` (slash dates only).
 */
